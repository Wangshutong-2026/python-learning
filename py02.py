# 1.变量的作用
# 计算机中的存储空间，用于保存数据
# 2.定义变量的格式
# 变量名 = 值
# 注意： =是赋值运算符，左右两边打上空格是为了代码的规范性，美观性
num1 = 3  #num1就是一个变量，保存可乐的价格
num2 = 10  #num2也是一个变量，保存冰淇淋的价格
total = num1 + num2  #total也是一个变量，保存总价格
print(num1)
#加上引号会打印引号里面的内容，没有引号就会被识别成变量名，打印的是变量的值
# 如果该变量没有被赋值，就会报命名错误
# 变量只有在赋值以后才会被创建，所以使用变量之前必须要赋值

a = 666
# 解释器做了两件事情
# 1.在内存中创建了一个666的数据
# 2.创建了一个变量a，把666这个数据保存到a变量中去
b = a
print(b)
print(a)  #666
a = 999   #同一个变量可以反复赋值
print(a)  #999

a = "哈哈"
