# 5.格式化输出
# 5.1占位符
# 生成一定格式的字符串
# 5.2 %
# 1. %s 字符串（常用）
name = 'shutong'
print("我的名字%s" % name)
# 注意：占位符只是占据位置，并不会被输出
# 2. %d 整数（常用）
age = 20
name = '姝彤'
print('我的名字是%s，年龄是%d' % (name,age))  #不要弄混顺序
# 3. %4d 整数
# 数字设置位数，不足前面补空白
a = 123
print('%010d' % a) #表示输出的整数显示位数，不足的话用0补全超出当前位数则原样输出
# 4. %f 浮点数（常用）
a = 1.2345673
print("%f" % a)
# 默认后六位小数，遵循四舍五入原则
# 5. %.4f 浮点数
# 数字设置小数位数，遵循四舍五入原则
b = 2.34567
print("%.7f" % b) #默认显示及7位小数
# 6. %%
print('我是%%的1%%' %())  #转义，输出%
# 5.3 f格式化
# 格式：f"{表达式}"
name = 'shutong'
age = 20
print(f"我的名字是{name}，我今年{age}岁了")

