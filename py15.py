# 1.面向对象和面向过程的区别
# 面向过程（手洗）：需要实现一个功能的时候，着重的是过程，分析出一个个步骤，并把一个个步骤
#                用一个个函数实现，再依次去调用一个个函数即可（每一个步骤都需要自己亲力亲为）
# 面向对象（机洗）：需要实现一个功能的时候，着重的是谁去帮我做这件事情（偷懒，找别人帮我做）
