# 3.for循环
# 基本格式
# for 临时变量 in 可迭代对象:
#     循环体
# 注意冒号和缩进
str = '1234'  #定义一个字符串
# 可迭代对象就是要去遍历取值的整体，现在的话只需要记住字符串就是可迭代对象
for i in str:  #i是临时变量，可以随便写，i是常规写法
    print(i)

# 3.2 range()
# 用来记录循环次数，相当于一个计数器
# for i in range(1,6):  #从1开始，从6-1结束，遵循包前不包后规则，[)
#     print("永远18岁")
# 包前不包后：包含开始位置的数字，不包含结束位置的数字
# range()里面只写一个数，这个数就是循环次数，默认从0开始
# 写两个数，前面的数字代表开始位置，后面的数字代表结束位置

# 3.3for循环应用：计算计算1+2+3+...+100的和的值
s = 0  #定义一个变量来保存计算结果
for i in range(1,101):  #包前不包后，不包含101这个数，从1-100
    # print(i)
    s += i  #每循环一次计算成果与i进行相加
    # print("计算结果：", s)
print("计算结果：",s)
# 相比之下，for循环比while循环更简便一点，更常见

# 5.break和continue关键字
# 都是专门在循环中使用的关键字
# i = 1
# if i <= 5:
#     print("我在吃苹果")
#     break
#报错，break和continue只能放在循环内
# 5.1 break
# 作用：某一条件满足时，退出循环
i = 1
while i <= 5:
    print(f"小红在吃第{i}个苹果")
    if i == 3:
        print("吃饱了不吃了")
        break  #结束break所在的循环
    i += 1
# 5.2 continue
# 作用：退出本次循环，下一次循环继续执行
i = 1
while i <= 5:
    print(f"小明在吃第{i}个苹果")
    if i == 3:
        print(f"吃到了一条大虫子，第{i}个苹果不吃了")
        #在continue之前，一定要修改计数器，否则会陷入死循环
        i += 1
        continue
    i += 1

for i in range(5):
    if i == 3:
        # break  #i=3时结束当前所在循环
        continue  #跳过3，结束了在3时的循环，继续执行下一次循环
    print(i)