# 1.3 while循环应用：计算1+2+3+...+100的和的值
i = 1  #定义一个初始值，从1开始计算，记录循环次数
s = 0  #定义一个变量保存计算结果，最开始计算结果为0，没有相加
while i <= 100:
    # print(i)  #循环打印1-100
    s += i  #每次循环的计算结果和i进行相加
    i += 1  #每循环一次，i的值加一
    # print('计算结果：', s)  #在循环内，循环输出计算结果
print('计算结果：',s)

